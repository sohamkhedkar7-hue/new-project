create table if not exists public.simulation_snapshots (
  id bigint generated by default as identity primary key,
  scenario jsonb not null,
  created_at timestamptz not null default now()
);

alter table public.simulation_snapshots enable row level security;

grant insert on table public.simulation_snapshots to anon;
grant usage, select on sequence public.simulation_snapshots_id_seq to anon;

create policy "Allow anonymous demo inserts"
  on public.simulation_snapshots
  for insert
  to anon
  with check (true);
